import { createHash } from 'node:crypto';

import type { Plugin } from 'vite';

/**
 * Drops the WOFF fallback from @fontsource stylesheets. Every supported browser reads
 * WOFF2, and the unused WOFF copies otherwise double the deployed size.
 */
export function woff2Only(): Plugin {
  return {
    name: 'kanjipain:woff2-only',
    enforce: 'pre',
    transform(code, id) {
      if (!id.includes('@fontsource') || !id.endsWith('.css')) return null;
      return {
        code: code.replace(/,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/g, ''),
        map: null,
      };
    },
  };
}

/** Files fetched only when needed; cached at runtime as they are used, never up front. */
function isRuntimeOnly(fileName: string, facadeModuleId: string | null | undefined): boolean {
  return (
    /\.(?:woff2?|map)$/.test(fileName) ||
    facadeModuleId?.includes('/src/data/stroke-shards/') === true ||
    fileName.startsWith('tests/')
  );
}

export function serviceWorkerSource(cacheName: string, precache: readonly string[]): string {
  return `// Generated by vite-plugins.ts. Offline support for KanjiPain.
const CACHE = ${JSON.stringify(cacheName)};
const RUNTIME = 'kanjipain-runtime';
const PRECACHE = ${JSON.stringify(precache)};

const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map(scoped)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('kanjipain-app-') && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

/** The app's own page; every route lives in its hash. */
function isAppShell(url) {
  const shell = new URL(scoped('./'));
  return url.pathname === shell.pathname || url.pathname === shell.pathname + 'index.html';
}

async function fromNetworkFirst(request) {
  const url = new URL(request.url);
  const key = isAppShell(url) ? scoped('./') : request;
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(isAppShell(url) ? CACHE : RUNTIME);
      await cache.put(key, response.clone());
    }
    return response;
  } catch (error) {
    const cached = await caches.match(key, { ignoreSearch: true, ignoreVary: true });
    if (cached !== undefined) return cached;
    throw error;
  }
}

async function fromCacheFirst(request) {
  const cached = await caches.match(request, { ignoreSearch: true, ignoreVary: true });
  if (cached !== undefined) return cached;
  const response = await fetch(request);
  // Stroke-data parts, fonts and license files are cached as they are first used.
  if (response.ok) {
    const cache = await caches.open(RUNTIME);
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !request.url.startsWith(self.registration.scope)) {
    return;
  }
  // The page itself comes from the network when possible, so a new release shows up on the
  // next visit; the cached copy keeps the app opening offline.
  if (request.mode === 'navigate') {
    event.respondWith(fromNetworkFirst(request));
    return;
  }
  event.respondWith(fromCacheFirst(request));
});
`;
}

/**
 * Emits \`sw.js\`, a service worker that precaches the app shell, catalog and Jōyō stroke
 * data so the app can start offline. Stroke-data shards for custom decks and font subsets
 * are cached at runtime instead, as they are fetched.
 */
export function offlineServiceWorker(): Plugin {
  return {
    name: 'kanjipain:service-worker',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = Object.values(bundle)
        .filter(
          (output) =>
            !isRuntimeOnly(output.fileName, output.type === 'chunk' ? output.facadeModuleId : null),
        )
        .map((output) => output.fileName)
        .filter((fileName) => !fileName.endsWith('.html'))
        .sort();
      const precache = ['./', ...files];
      const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 16);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(`kanjipain-app-${version}`, precache),
      });
    },
  };
}
